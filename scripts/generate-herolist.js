const fs = require('fs');
const path = require('path');
const https = require('https');

/**
 * 数据源：腾讯官方英雄联盟 CDN 核心数据
 * 包含：英文名(alias), 中文称号(name), 中文名(title), 角色标签(roles)
 */
const DATA_SOURCE_URL = 'https://game.gtimg.cn/images/lol/act/img/js/heroList/hero_list.js';
// 修改点：路径改为指向 apps/web/src/data/heroes.ts
const OUTPUT_FILE = path.join(__dirname, '../apps/web/src/data/heroes.ts');
const SERVER_HERO_POOL_FILE = path.join(__dirname, '../apps/server/src/heroPool.ts');

/**
 * ID 规范化
 * 确保生成的 id 与本地图片文件名（小写英文 alias）完全匹配。
 */
const ID_FIXES = {
  'MonkeyKing': 'monkeyking',
  'Renata': 'renata',
  'Nunu': 'nunu',
  'LeBlanc': 'leblanc',
  'KogMaw': 'kogmaw',
  'RekSai': 'reksai',
  'BelVeth': 'belveth',
  'Kaisa': 'kaisa',
  'Khazix': 'khazix'
};

/**
 * 抓取函数
 */
const fetchRawContent = (url) => {
  return new Promise((resolve, reject) => {
    const options = {
      headers: {
        'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36',
        'Referer': 'https://lol.qq.com/'
      }
    };
    https.get(url, options, (res) => {
      if (res.statusCode !== 200) {
        return reject(new Error(`无法访问网页: ${res.statusCode} (URL: ${url})`));
      }
      let data = '';
      res.on('data', chunk => data += chunk);
      res.on('end', () => resolve(data));
    }).on('error', reject);
  });
};

/**
 * 分路自动推断逻辑 (基于官方职业标签)
 */
const autoAssignRoles = (hero) => {
  const roles = new Set();
  const tags = hero.roles || [];
  const alias = hero.alias.toLowerCase();

  // 1. 基础映射
  if (tags.includes('tank') || tags.includes('fighter')) roles.add('TOP');
  if (tags.includes('mage') || tags.includes('assassin')) roles.add('MID');
  if (tags.includes('marksman')) roles.add('BOT');
  if (tags.includes('support')) roles.add('SUP');

  // 2. 自动化打野识别 (关键词)
  const jungleKeys = ['vi', 'viego', 'lee', 'khazix', 'rengar', 'hecarim', 'shaco', 'nidalee', 'elise', 'ivern', 'belveth', 'briar', 'skarner', 'rammus', 'warwick', 'kindred', 'lillia', 'nunu', 'amumu', 'volibear', 'udyr', 'trundle', 'evelynn', 'graves', 'gragas', 'jarvan', 'xin', 'masteryi', 'fiddlesticks', 'sejuani', 'zac', 'nocturne'];
  if (jungleKeys.some(k => alias.includes(k))) roles.add('JG');

  // 3. 特殊逻辑修正
  if (tags.includes('marksman') && !tags.includes('mage') && !tags.includes('fighter')) {
    roles.delete('MID');
    roles.add('BOT');
  }
  if (tags.includes('support') && (tags.includes('mage') || tags.includes('tank'))) {
    roles.delete('TOP');
    roles.delete('MID');
    roles.add('SUP');
  }

  const finalRoles = Array.from(roles);
  return finalRoles.length > 0 ? finalRoles : ['MID'];
};

const run = async () => {
  console.log('🚀 正在从腾讯官方 CDN 抓取全量英雄数据（含中文内容）...');

  try {
    const rawContent = await fetchRawContent(DATA_SOURCE_URL);

    // 解析 JSON
    const data = JSON.parse(rawContent);
    const champions = data.hero || [];

    if (champions.length === 0) {
      throw new Error('抓取到的英雄列表为空。');
    }

    console.log(`成功获取到 ${champions.length} 位英雄的原始记录。`);

    // 过滤并处理英雄数据
    const heroList = champions
      .filter(c => c.alias && c.alias !== 'None')
      .sort((a, b) => a.alias.localeCompare(b.alias))
      .map(c => {
        const id = ID_FIXES[c.alias] || c.alias.toLowerCase();
        return {
          id,
          name: c.alias,       // 英文别名 (Aatrox)
          nameCn: c.title,     // 中文名 (亚托克斯)
          titleCn: c.name,     // 中文称号 (暗裔剑魔)
          roles: autoAssignRoles(c)
        };
      });

    // 生成 TS 代码内容
    const fileContent = `
/**
 * Auto-generated by scripts/generate-herolist.js
 * Source: Tencent LOL Official CDN (gtimg.cn)
 * Total Heroes: ${heroList.length}
 * Generated at: ${new Date().toLocaleString()}
 */

export interface Hero {
  id: string;
  name: string;
  nameCn: string;
  titleCn: string;
  roles: string[];
}

export const RAW_HEROES: Hero[] = ${JSON.stringify(heroList, null, 2)};
`;

    fs.writeFileSync(OUTPUT_FILE, fileContent.trim());

    const heroIds = heroList.map((hero) => hero.id);
    const serverPoolContent = `// Auto-generated from apps/web/src/data/heroes.ts.
// Keep this file in sync by running scripts/generate-herolist.js.

export const HERO_IDS = ${JSON.stringify(heroIds, null, 2)} as const;

export type HeroId = (typeof HERO_IDS)[number];
export const HERO_ID_SET = new Set<string>(HERO_IDS);
`;
    fs.writeFileSync(SERVER_HERO_POOL_FILE, serverPoolContent);

    console.log('\n✨ 英雄列表（含中文）同步完成！');
    console.log(`保存路径: ${OUTPUT_FILE}`);
    console.log(`服务端英雄池: ${SERVER_HERO_POOL_FILE}`);
    console.log('-------------------------------------------');
    console.log('📊 同步详情:');
    console.log(`- 英雄总数: ${heroList.length}`);
    console.log(`- 中文支持: ✅ 已同步 (包含：中文名、称号)`);
    console.log('-------------------------------------------');

  } catch (error) {
    console.error('❌ 抓取数据时发生错误:', error.message);
  }
};

run();
